// Задаётся ли вопрос при таких ответах (условные вопросы — через when).
export const isActive = (step, answers) => !step.when || step.when(answers);

export const wantsCopy = (answers) => answers.send_copy === COPY_YES;

export function nextStepIndex(from, answers) {
  for (let i = from; i < STEPS.length; i++) {
    if (isActive(STEPS[i], answers)) return i;
  }
  return -1;
}

// Первый вопрос, который должен быть задан, но ещё без ответа.
// Нужен после исправления ответа: например, выбрали «Несколько локаций» — спросим, сколько.
export function firstMissingIndex(answers) {
  return STEPS.findIndex((s) => isActive(s, answers) && answers[s.id] === undefined);
}
